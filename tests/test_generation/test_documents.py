import pytest

from agent_sync.document import parse_markdown
from agent_sync.models.document import FrontMatterValues
from agent_sync.generation.artifact import generate_agents, generate_hooks
from agent_sync.generation.rule import (
    generate_codex_rules,
    generate_rule_mirrors,
    generate_shared_rule_outputs,
)
from agent_sync.models.output import ArtifactKind, GeneratedFile, Harness
from agent_sync.models.settings import Workspace
from agent_sync.workspace import agents_dir, models_dir, settings_dir
from tests.factories import HooksConfigFactory, RuleFrontMatterFactory, materialize_rule, load_context


class TestDocumentGeneration:
    """Test that agents, rules, and hooks use their artifact formats."""

    def test_agent_model_override_precedes_harness_default(
        self,
        workspace: Workspace,
    ) -> None:
        """Test that agent-specific models override harness-wide settings."""

        agent_sources = agents_dir(workspace) / "agents"
        agent_sources.mkdir()
        (agent_sources / "review.md").write_text("---\nname: review\n---\n\nReview.\n")
        settings_dir(workspace).mkdir()
        (settings_dir(workspace) / "claude.json").write_text('{"model":"default"}')
        models_dir(workspace).mkdir()
        (models_dir(workspace) / "review.json").write_text(
            '{"claude_code":"override","cursor":"cursor-model"}'
        )

        context = load_context(workspace)
        outputs = [
            *generate_agents(context, Harness.CLAUDE_CODE),
            *generate_agents(context, Harness.CURSOR),
        ]
        files = {output.harness: output.content for output in outputs if isinstance(output, GeneratedFile)}

        assert "model: override" in files[Harness.CLAUDE_CODE]
        assert "model: cursor-model" in files[Harness.CURSOR]

        assert all(
            "\n---\n\n<!-- Generated by [Agent Sync Action]"
            "(https://github.com/julien777z/agent-sync-action). "
            "Do not edit this file directly. -->\n\nReview." in content
            for content in files.values()
        )

    def test_unscoped_rules_render_harness_mirrors_without_changing_sources(
        self,
        workspace: Workspace,
    ) -> None:
        """Render native rule files while preserving canonical source text."""

        source = agents_dir(workspace) / "rules/python.md"
        materialize_rule(source, RuleFrontMatterFactory.build(name="removed", always_apply=False))
        original = source.read_text()
        context = load_context(workspace)
        outputs = [
            *generate_shared_rule_outputs(context),
            *generate_rule_mirrors(context, Harness.CLAUDE_CODE),
            *generate_rule_mirrors(context, Harness.CURSOR),
        ]
        mirrors = [
            output
            for output in outputs
            if isinstance(output, GeneratedFile) and output.artifact is ArtifactKind.RULE
        ]

        assert source.read_text() == original
        assert len(mirrors) == 2
        assert {mirror.target_path.suffix for mirror in mirrors} == {".md", ".mdc"}
        assert all(source.read_text().split("---", 2)[2].strip() in mirror.content for mirror in mirrors)

    def test_codex_rules_render_starlark_without_markdown_body(
        self,
        workspace: Workspace,
    ) -> None:
        """Test that a Starlark-only rule still generates its Codex output."""

        rules_dir = agents_dir(workspace) / "rules"
        rules_dir.mkdir()
        source = rules_dir / "git.md"
        source.write_text('---\nstarlark: |\n  allow_rule(prefix_rule = ["git", "status"])\n' "---\n")

        context = load_context(workspace)
        outputs = generate_codex_rules(context, Harness.CODEX)

        assert len(outputs) == 1
        assert isinstance(outputs[0], GeneratedFile)
        assert outputs[0].target_path == workspace.root / ".codex/rules/git.rules"

        assert outputs[0].content.startswith(
            "# Generated by [Agent Sync Action]"
            "(https://github.com/julien777z/agent-sync-action). "
            "Do not edit this file directly.\n"
            "# Source: .agents/rules/git.md\n"
        )
        assert 'allow_rule(prefix_rule = ["git", "status"])' in outputs[0].content
        shared_outputs = generate_shared_rule_outputs(context)

        assert not shared_outputs
        assert not generate_rule_mirrors(context, Harness.CLAUDE_CODE)
        assert not generate_rule_mirrors(context, Harness.CURSOR)

    @pytest.mark.parametrize(
        ("scope", "patterns"),
        [
            ('paths: "**/*.py"', ["**/*.py"]),
            ('paths: ["**/*.py"]', ["**/*.py"]),
            ('globs: "**/*.py"', ["**/*.py"]),
            ('globs: ["**/*.py"]', ["**/*.py"]),
            ('globs: "**/*.py"\npaths: "**/*.py"', ["**/*.py"]),
            ('globs: "**/*.ts"\npaths: "**/*.py"', ["**/*.py"]),
            ('globs: "**/*.ts"\npaths: null', []),
            ("globs: null", []),
        ],
        ids=[
            "string",
            "list",
            "alias-string",
            "alias-list",
            "both",
            "paths-priority",
            "null-priority",
            "null-alias",
        ],
    )
    def test_rule_scope_inputs_render_native_metadata(
        self, workspace: Workspace, scope: str, patterns: list[str]
    ) -> None:
        """Resolve accepted scope inputs once before rendering either harness."""

        source = agents_dir(workspace) / "rules/python.md"
        source.parent.mkdir()
        source.write_text(f"---\n{scope}\nalwaysApply: false\n---\n\n# Rule\n")
        original = source.read_bytes()
        context = load_context(workspace)

        for harness, scope_key, other_key in (
            (Harness.CLAUDE_CODE, "paths", "globs"),
            (Harness.CURSOR, "globs", "paths"),
        ):
            outputs = generate_rule_mirrors(context, harness)

            assert len(outputs) == 1
            assert isinstance(outputs[0], GeneratedFile)
            metadata, body = parse_markdown(
                outputs[0].content, FrontMatterValues, str(outputs[0].target_path)
            )
            assert metadata.root.get(scope_key, []) == patterns
            assert other_key not in metadata.root
            assert metadata.root["alwaysApply"] is False
            assert body.endswith("# Rule")

        assert source.read_bytes() == original

    def test_rule_paths_annotate_root_instructions(
        self,
        workspace: Workspace,
    ) -> None:
        """Use the canonical scope to tell Codex when to read a rule."""

        source = agents_dir(workspace) / "rules/python.md"
        source.parent.mkdir(parents=True)
        source.write_text('---\npaths: ["**/*.py", "**/*.pyi"]\nalwaysApply: false\n---\n\n# Rule\n')

        context = load_context(workspace)
        instructions = next(
            output
            for output in generate_shared_rule_outputs(context)
            if isinstance(output, GeneratedFile) and output.artifact is ArtifactKind.INSTRUCTIONS
        )

        assert (
            "Read `.agents/rules/python.md` for files matching `**/*.py`, `**/*.pyi`" in instructions.content
        )

    @pytest.mark.parametrize("harness", list(Harness))
    @pytest.mark.parametrize(
        ("filename", "content", "mode", "executable"),
        [
            ("check", "#!/usr/bin/env python3\nprint('ok')\n", 0o644, True),
            ("scripts/check.sh", "echo ready\n", 0o644, True),
            ("scripts/check", "echo ready\n", 0o755, True),
            ("resources/context.md", "Context.\n", 0o644, False),
        ],
        ids=["shebang", "shell-extension", "source-mode", "supporting-text"],
    )
    def test_hooks_preserve_executable_intent(
        self,
        workspace: Workspace,
        harness: Harness,
        filename: str,
        content: str,
        mode: int,
        executable: bool,
    ) -> None:
        """Test that shell and shebang hooks are marked executable."""

        hooks_dir = agents_dir(workspace) / "hooks"
        source = hooks_dir / filename
        source.parent.mkdir(parents=True)
        source.write_text(content)
        source.chmod(mode)
        config = HooksConfigFactory.build()
        config.hooks["SessionStart"][0].hooks[0].command = f'python3 ".agents/hooks/{filename}"'
        (hooks_dir / "hooks.json").write_text(config.model_dump_json(exclude_none=True))

        context = load_context(workspace)
        outputs = generate_hooks(context, harness)

        output = next(
            output
            for output in outputs
            if output.target_path == harness.root(workspace.root) / "hooks" / filename
        )

        assert isinstance(output, GeneratedFile)
        assert output.target_path == harness.root(workspace.root) / "hooks" / filename
        assert output.content == content
        assert output.executable is executable
